import { expect, test } from '@playwright/test'

test('dedicated rule page preserves generated IDs, edits, priority, and management', async ({ page }, testInfo) => {
  await page.setExtraHTTPHeaders({ 'X-Test-Client': testInfo.testId })
  await page.goto('/')
  await page.getByTestId('login-password').fill('test-admin-password')
  await page.getByTestId('login-submit').click()
  await expect(page.getByTestId('app-header')).toBeVisible()
  const session = await (await page.request.get('/api/session')).json()
  const headers = { 'X-CSRF-Token': session.csrf_token }
  const response = await page.request.post('/api/accounts', { headers, data: {
    provider: 'vesync', label: 'Rule test', email: 'rules-e2e@example.com', password: 'fake-provider', country_code: 'SG', time_zone: 'Asia/Singapore',
  } })
  expect(response.status()).toBe(201)
  const account = await response.json()
  try {
    await page.reload()
    const card = page.getByTestId('device-card').filter({ hasText: 'Rule test purifier' })
    await expect(card.getByTestId('automation-rule')).toHaveCount(0)
    await card.getByTestId('device-rules-link').click()
    await expect(page).toHaveURL(/\/devices\/[^/]+\/rules$/)
    const editor = page.getByTestId('rules-page')
    await expect(page.getByTestId('page-title')).toHaveText('Rule test purifier rules')
    await expect(page.getByTestId('devices-section')).toHaveCount(0)
    await expect(editor.getByTestId('automation-enable')).toBeDisabled()
    await editor.getByTestId('rule-add').click()
    const rules = editor.getByTestId('automation-rule')
    await expect(editor.getByTestId('rule-id')).toHaveCount(0)
    await expect(editor.getByTestId('rule-trigger-id')).toHaveCount(0)
    await rules.first().getByTestId('rule-explanation').fill('Assist when outdoor AQI is high')
    await rules.first().getByTestId('rule-add-condition').click()
    await rules.first().getByTestId('rule-source').selectOption('outdoor')
    await rules.first().getByTestId('rule-at-least').fill('100')
    await rules.first().getByTestId('rule-action').selectOption('4')
    await editor.getByTestId('rule-add').click()
    await rules.nth(1).getByTestId('rule-explanation').fill('Clean elevated indoor readings')
    await rules.nth(1).getByTestId('rule-add-condition').click()
    await rules.nth(1).getByTestId('rule-at-least').fill('5')
    await rules.nth(1).getByTestId('rule-action').selectOption('3')
    page.once('dialog', async dialog => {
      expect(dialog.type()).toBe('beforeunload')
      await dialog.dismiss()
    })
    await editor.getByTestId('rules-back').click()
    await expect(page).toHaveURL(/\/devices\/[^/]+\/rules$/)
    await expect(rules).toHaveCount(2)
    await editor.getByTestId('automation-preview').click()
    await expect(editor.getByTestId('automation-preview-result')).toContainText('Clean elevated indoor readings')
    await rules.nth(1).getByTestId('rule-up').click()
    await expect(rules.first().getByTestId('rule-explanation')).toHaveValue('Clean elevated indoor readings')
    await rules.first().getByTestId('rule-below').fill('4')
    await editor.getByTestId('automation-save').click()
    await expect(editor.getByTestId('automation-error')).toContainText('upper bound')
    await rules.first().getByTestId('rule-below').fill('')
    await editor.getByText('Timing & location', { exact: true }).click()
    await expect(editor.getByTestId('rule-timezone')).toHaveValue('Asia/Singapore')
    await editor.getByTestId('rule-consecutive-readings').fill('1')
    await editor.getByTestId('automation-save').click()
    await expect(editor.getByTestId('automation-notice')).toHaveText('Rules saved.')
    await expect(editor.getByTestId('automation-draft-status')).toHaveText('Saved')
    const deviceId = page.url().split('/').at(-2)!
    const path = '/api/devices/' + deviceId + '/automation'
    const firstSaved = (await (await page.request.get(path)).json()).ruleset
    expect(new Set(firstSaved.rules.map((r: { id: string }) => r.id)).size).toBe(2)
    await rules.first().getByTestId('rule-down').click()
    await editor.getByTestId('automation-save').click()
    await expect(editor.getByTestId('automation-draft-status')).toHaveText('Saved')
    const reordered = (await (await page.request.get(path)).json()).ruleset
    expect(reordered.rules.map((r: { id: string }) => r.id)).toEqual([...firstSaved.rules.map((r: { id: string }) => r.id)].reverse())
    await page.reload()
    await expect(rules.first().getByTestId('rule-explanation')).toHaveValue('Assist when outdoor AQI is high')
    await expect(rules.nth(1).getByTestId('rule-expand')).toHaveAttribute('aria-expanded', 'false')
    await rules.nth(1).getByTestId('rule-expand').click()
    await expect(rules.nth(1).getByTestId('rule-at-least')).toHaveValue('5')
    await editor.getByTestId('automation-enable').click()
    await expect(editor.getByTestId('automation-status')).toHaveText('Manual')
    await editor.getByTestId('automation-pause').click()
    await expect(editor.getByTestId('automation-pause-status')).toContainText('Paused until')
    await editor.getByTestId('automation-resume').click()
    await expect(editor.getByTestId('automation-pause-status')).toHaveCount(0)
    await editor.getByText('Management', { exact: true }).click()
    await editor.getByTestId('automation-ownership').click()
    await expect(editor.getByTestId('automation-status')).toHaveText('Agent-managed')
    await expect(rules.first().getByTestId('rule-explanation')).toBeDisabled()
    await rules.nth(1).getByTestId('rule-expand').click()
    await expect(rules.nth(1).getByTestId('rule-expand')).toHaveAttribute('aria-expanded', 'false')
    await rules.nth(1).getByTestId('rule-expand').click()
    await expect(rules.nth(1).getByTestId('rule-at-least')).toBeVisible()
    await expect(rules.nth(1).getByTestId('rule-at-least')).toBeDisabled()
    await expect(editor.getByTestId('automation-review-status')).toBeVisible()
    await editor.getByTestId('automation-ownership').click()
    await expect(rules.first().getByTestId('rule-explanation')).toBeEnabled()
    await editor.getByTestId('automation-pause').click()
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: testInfo.outputPath('rules-desktop.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
    await page.screenshot({ path: testInfo.outputPath('rules-mobile.png'), fullPage: true })
    await editor.getByTestId('rules-back').click()
    await expect(page).toHaveURL(/\/$/)
    await expect(card.getByTestId('device-rules-link')).toBeVisible()
    await expect(card.getByTestId('automation-rule')).toHaveCount(0)
  } finally {
    await page.request.delete(`/api/accounts/${account.id}`, { headers })
  }
})
